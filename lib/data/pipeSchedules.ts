export function getPipeByNps(nps: string): PipeEntry | undefined {
  return PIPE_SCHEDULES.find((p) => p.nps === nps);
}

export function getWall(nps: string, schedule: string): number | undefined {
  const pipe = getPipeByNps(nps);
  return pipe?.schedules.find((s) => s.schedule === schedule)?.wall;
}
